// ─── 2. THE PROMO CLIFF ───────────────────────────────────────────────────────────────────────

/** Tre's real Discover: $5,037.73 at 7.99% until 2028-01-04 against a 16.6% standard rate. */
function discover(promoEnd: string | null): CardData {
  return makeCard({
    id: 'discover', name: 'Discover', balance: 10316.73, apr: 16.6,
    minPayment: 229, minPaymentIsManual: true, targetPayment: 229, dueDay: 1,
    tranches: [tranche({ id: 'bt', label: 'Balance transfer', balance: 5037.73, apr: 7.99, promo_end_date: promoEnd })],
  });
}

/** Minimum-only every month: the cap pins the cascade to exactly the $229 contract minimum. */
function runDiscover(card: CardData, months: number) {
  return simulateVariablePayoff(
    [card], 2000, 0, 'avalanche', 1500, 500, months,
    Array.from({ length: months }, () => ({ income: 1500, expenses: 500 })),
    undefined, undefined, undefined, undefined, undefined, undefined,
    Array.from({ length: months }, () => 229), // maxDebtPaymentByMonth
  );
}

describe('simulateVariablePayoff — per-tranche accrual and repricing at the promo cliff', () => {
  afterEach(() => vi.useRealTimers());

  it('shows the interest step in the month the promo expires (Discover, Jan 2028)', () => {
    vi.useFakeTimers({ toFake: ['Date'] });
    vi.setSystemTime(new Date(2027, 10, 15, 12, 0, 0)); // Nov 15 2027 — m0=Nov, m1=Dec, m2=Jan 2028

    const sim = runDiscover(discover('2028-01-04'), 4);
    const interest = sim.monthlyInterest.get('discover')!;
    const balances = sim.monthlyBalances.get('discover')!;
    const payments = sim.monthlyPayments.get('discover')!;

    // Every month pays exactly the $229 contract minimum (manual ⇒ exact, and the cap holds the
    // cascade there), so the whole walk is determined by the interest split.
    expect(payments).toEqual([229, 229, 229, 229]);

    // m0 — Nov 2027, rates as of 2027-11-30, promo still live.
    //   tranche  5,037.73 × 7.99%/12 =  33.5428856
    //   remainder (10,316.73 − 5,037.73 = 5,279.00) × 16.6%/12 = 73.0261667
    //   total 106.5690523 → 106.57      (a single-APR card at 16.6% would charge 142.71 — below)
    //   end balance 10,316.73 + 106.57 − 229 = 10,194.30
    expect(interest[0]).toBe(106.57);
    expect(balances[0]).toBe(10194.30);

    // m1 — Dec 2027, rates as of 2027-12-31, promo STILL live (2027-12-31 < 2028-01-04).
    //   the tranche compounded at its own rate: 5,037.73 + 33.54 = 5,071.27
    //   tranche  5,071.27 × 7.99%/12 = 33.7662061
    //   remainder (10,194.30 − 5,071.27 = 5,123.03) × 16.6%/12 = 70.8685817
    //   total 104.6347878 → 104.63
    //   end balance 10,194.30 + 104.63 − 229 = 10,069.93
    expect(interest[1]).toBe(104.63);
    expect(balances[1]).toBe(10069.93);

    // m2 — Jan 2028, rates as of 2028-01-31 ≥ 2028-01-04 ⇒ THE TRANCHE REPRICES to 16.6%.
    //   tranche  (5,071.27 + 33.77 = 5,105.04) × 16.6%/12 = 70.6197200
    //   remainder (10,069.93 − 5,105.04 = 4,964.89) × 16.6%/12 = 68.6809783
    //   total 139.3006983 → 139.30 — a +$34.67 step against December, in the month it happens.
    expect(interest[2]).toBe(139.30);
    expect(Math.round((interest[2] - interest[1]) * 100) / 100).toBe(34.67);

    // m3 — Feb 2028: both buckets at 16.6% now, so the split is arithmetically the flat rate again.
    //   balance 10,069.93 + 139.30 − 229 = 9,980.23 → × 16.6%/12 = 138.0598483 → 138.06
    expect(balances[2]).toBe(9980.23);
    expect(interest[3]).toBe(138.06);

    // …and the step survives into the rendered projection rows (what Forecast/the debt table read),
    // not just the sim's internal series.
    const rows = projectCardVariable(
      discover('2028-01-04'), payments, 4, true, undefined,
      sim.monthlyRevolvingBalances.get('discover')!,
      sim.monthlyCyclingOwed.get('discover')!, sim.monthlyCyclingInterest.get('discover')!,
      balances, interest,
    ).months;
    expect(rows.map(r => r.interest)).toEqual([106.57, 104.63, 139.30, 138.06]);
    // (Feb's end balance: 9,980.23 + 138.06 − 229 = 9,889.29.)
    expect(rows.map(r => r.endBalance)).toEqual([10194.30, 10069.93, 9980.23, 9889.29]);
  });

  it('leaves the promo tranche untouched while the minimum is being paid (CARD Act §164)', () => {
    vi.useFakeTimers({ toFake: ['Date'] });
    vi.setSystemTime(new Date(2027, 10, 15, 12, 0, 0));

    // The $229 goes to the 16.6% remainder, never the 7.99% tranche — which is exactly why the
    // tranche is still there at the cliff. If it were being paid down, m1's tranche interest would
    // be lower than m0's; instead it RISES (33.54 → 33.77) because it compounds untouched.
    const sim = runDiscover(discover('2028-01-04'), 2);
    const interest = sim.monthlyInterest.get('discover')!;
    // m1's total (104.63) minus the remainder's share on 5,123.03 (70.87) leaves the tranche's
    // 33.76 — a cent under its own 33.77 because the two sides round separately, and comfortably
    // above m0's 33.54, i.e. the tranche GREW rather than shrank.
    expect(Math.round((interest[1] - 70.87) * 100) / 100).toBe(33.76);
  });

  it('bites: with no promo_end_date the same card never steps up', () => {
    vi.useFakeTimers({ toFake: ['Date'] });
    vi.setSystemTime(new Date(2027, 10, 15, 12, 0, 0));

    // Identical card, permanent 7.99% (promo_end_date null). The ledger walk through m0/m1 is
    // identical (same rates), so Jan 2028 isolates repricing alone:
    //   tranche 5,105.04 × 7.99%/12 = 33.9910580  (vs 70.6197200 repriced)
    //   remainder 4,964.89 × 16.6%/12 = 68.6809783
    //   total 102.6720363 → 102.67
    // Delete the cliff handling (trancheAprAsOf inside trancheInterestBreakdown) and the FIRST
    // test's m2 becomes this number — 102.67 instead of 139.30, $36.63/month understated forever.
    const sim = runDiscover(discover(null), 4);
    expect(sim.monthlyInterest.get('discover')![2]).toBe(102.67);
  });
});

// ─── 3. AVALANCHE ORDER FLIP ──────────────────────────────────────────────────────────────────

describe('simulateVariablePayoff — avalanche ranks on the MARGINAL rate', () => {
  afterEach(() => vi.useRealTimers());

  // LOW's stated APR (10%) sorts it behind MID (18%) under the single-APR model, but two thirds of
  // LOW's balance sits at 25.99% and that is where the next dollar lands (CARD Act §164). The
  // surplus therefore belongs to LOW.
  const lowTranche = tranche({ id: 'bt', label: 'Cash advance', balance: 4000, apr: 25.99 });
  const makePair = (withTranches: boolean): CardData[] => [
    makeCard({ id: 'LOW', name: 'Low stated APR', balance: 6000, apr: 10, minPayment: 100,
      minPaymentIsManual: true, targetPayment: 100, ...(withTranches ? { tranches: [lowTranche] } : {}) }),
    makeCard({ id: 'MID', name: 'Mid APR', balance: 6000, apr: 18, minPayment: 100,
      minPaymentIsManual: true, targetPayment: 100 }),
  ];
  const run = (cards: CardData[]) => simulateVariablePayoff(
    cards, 3000, 0, 'avalanche', 2000, 0, 2,
    [{ income: 2000, expenses: 0 }, { income: 2000, expenses: 0 }],
  );

  it('sends the surplus to the card carrying the expensive tranche', () => {
    vi.useFakeTimers({ toFake: ['Date'] });
    vi.setSystemTime(new Date(2026, 7, 14, 12, 0, 0));

    // Pool: 3,000 cash + 2,000 income = 5,000, drained not to the $0 floor but to the floor plus
    // FLOOR_CUSHION_DOLLARS (2026-08-21: month 0 is cushioned like every other month, see
    // step5Floor in credit-card-engine.ts). Minimums 100 + 100, so the surplus is 4,798, not 4,800.
    const flipped = run(makePair(true));
    expect(flipped.monthlyPayments.get('LOW')![0]).toBe(4898);
    expect(flipped.monthlyPayments.get('MID')![0]).toBe(100);

    // Control: the SAME cards without the tranche sort the other way round, 18% before 10%.
    const control = run(makePair(false));
    expect(control.monthlyPayments.get('MID')![0]).toBe(4898);
    expect(control.monthlyPayments.get('LOW')![0]).toBe(100);

    // And the money lands where §164 says: m0 interest on LOW is
    //   4,000 × 25.99%/12 = 86.6333 + 2,000 × 10%/12 = 16.6667 → 103.30
    // (a single-APR read of the same card charges 6,000 × 10%/12 = 50.00 — the understatement).
    expect(flipped.monthlyInterest.get('LOW')![0]).toBe(103.30);
    expect(control.monthlyInterest.get('LOW')![0]).toBe(50);

    // The 4,898 clears the 25.99% bucket first (4,086.63 = 4,000 + its 86.63 of interest), leaving
    // 811.37 for the remainder, so month 1 accrues on the 10% money alone:
    //   end balance 6,000 + 103.30 − 4,898 = 1,205.30 → × 10%/12 = 10.0442 → 10.04
    expect(flipped.monthlyBalances.get('LOW')![0]).toBe(1205.30);
    expect(flipped.monthlyInterest.get('LOW')![1]).toBe(10.04);
  });
});

// ─── 4. PARTIAL-ISB GRACE ─────────────────────────────────────────────────────────────────────

describe('simulateVariablePayoff — partial-ISB grace accrues on the shortfall only', () => {
  afterEach(() => vi.useRealTimers());

  it('charges the uncovered statement money, not the whole balance', () => {
    vi.useFakeTimers({ toFake: ['Date'] });
    vi.setSystemTime(new Date(2026, 7, 14, 12, 0, 0));

    // Prime Visa shape: a statement-preference card in grace whose available cash covers only part
    // of the statement. The cap holds every month's payment at exactly $1,000.
    const card = makeCard({
      id: 'prime', name: 'Prime Visa', balance: 3000, apr: 27.49, minPayment: 25, targetPayment: 25,
      monthlyNewPurchases: 500, paymentPreference: 'statement', statementBalancePhase: true, dueDay: 20,
    });
    const months = 3;
    const sim = simulateVariablePayoff(
      [card], 5000, 0, 'avalanche', 2000, 0, months,
      Array.from({ length: months }, () => ({ income: 2000, expenses: 0 })),
      undefined, undefined, undefined, undefined, undefined, undefined,
      Array.from({ length: months }, () => 1000),
    );
    const interest = sim.monthlyInterest.get('prime')!;
    const balances = sim.monthlyBalances.get('prime')!;

    expect(sim.monthlyPayments.get('prime')!.slice(0, 3)).toEqual([1000, 1000, 1000]);

    // m0 — in grace, nothing accrues (unchanged). Statement due 3,000, paid 1,000 ⇒ the card
    //      leaves grace carrying a 2,000 shortfall. End balance 2,000.
    expect(interest[0]).toBe(0);
    expect(balances[0]).toBe(2000);

    // m1 — only the shortfall accrues: 2,000 × 27.49%/12 = 45.8166 → 45.82. (Here the shortfall
    //      IS the whole balance, so the old grace-or-nothing model agrees.)
    //      Statement due 2,000 + 45.82 = 2,045.82, paid 1,000 ⇒ shortfall 1,045.82.
    //      End balance 2,000 + 45.82 + 500 purchases − 1,000 = 1,545.82.
    expect(interest[1]).toBe(45.82);
    expect(balances[1]).toBe(1545.82);

    // m2 — THE ONE THAT MOVES. Balance is 1,545.82 but only 1,045.82 of it is uncovered statement;
    //      the $500 of new purchases is still inside the grace period.
    //        1,045.82 × 27.49%/12 = 23.9580 → 23.96
    //      The old grace-or-nothing model charged the whole balance: 1,545.82 × 27.49%/12 = 35.41.
    //      Revert the partial model and this assertion reads 35.41 — that is the bite.
    expect(interest[2]).toBe(23.96);
    expect(interest[2]).toBeLessThan(35.41);
  });

  it('returns to full grace the moment a payment covers the statement', () => {
    vi.useFakeTimers({ toFake: ['Date'] });
    vi.setSystemTime(new Date(2026, 7, 14, 12, 0, 0));

    const card = makeCard({
      id: 'prime', name: 'Prime Visa', balance: 3000, apr: 27.49, minPayment: 25, targetPayment: 25,
      monthlyNewPurchases: 500, paymentPreference: 'statement', statementBalancePhase: true, dueDay: 20,
    });
    // Month 0 underpays ($1,000 of a $3,000 statement); month 1 has enough to clear everything.
    const sim = simulateVariablePayoff(
      [card], 5000, 0, 'avalanche', 2000, 0, 4,
      Array.from({ length: 4 }, () => ({ income: 2000, expenses: 0 })),
      undefined, undefined, undefined, undefined, undefined, undefined,
      [1000, 99999, 99999, 99999],
    );
    const interest = sim.monthlyInterest.get('prime')!;
    expect(interest[1]).toBe(45.82);  // the shortfall month's charge
    // m1 pays the full 2,045.82 statement ⇒ grace is restored and nothing accrues afterwards.
    expect(interest[2]).toBe(0);
    expect(interest[3]).toBe(0);
  });
});

