// Golden tests for handoff item 3 — the engine's multi-rate (balance_tranches) integration.
//
// Every number below is hand-walked in the comment above the assertion, so a future change that
// moves one has to explain which step of the arithmetic it disagrees with. The engine's own
// long-standing rules (cash floor, look-ahead, month-0 sync, sub-dollar dust) are unchanged and
// covered by the rest of the suite; what these tests pin is:
//   1. PARITY  — a card with no tranches produces byte-identical numbers to the pre-tranche
//      engine. These values were generated by running the pre-change credit-card-engine.ts on
//      this exact fixture; they are not "whatever it does now".
//   2. per-tranche accrual and repricing at the promo cliff (Tre's real Discover).
//   3. avalanche ordering by MARGINAL rate, which a tranche can flip.
//   4. partial-ISB grace — the uncovered statement money accrues, not the whole balance.
//   5. sub-dollar residuals still zero out on a multi-rate card.

const CARD_BASE = {
  creditLimit: 10000, monthlyRepayments: 0, color: '#000',
  autopayFullBalance: false, statementBalancePhase: false, statementBalance: null,
  steadyMonthlyPurchases: 0, monthlyNewPurchases: 0, paymentPreference: null,
} as const;

function makeCard(overrides: Partial<CardData> & Pick<CardData, 'id'>): CardData {
  return {
    ...CARD_BASE, name: overrides.id, balance: 0, apr: 0,
    minPayment: 25, targetPayment: 25, dueDay: 15,
    ...overrides,
  } as CardData;
}

function tranche(overrides: Partial<BalanceTranche>): BalanceTranche {
  return { id: 't', label: 'Promo balance', balance: 0, apr: 0, promo_end_date: null, ...overrides };
}

